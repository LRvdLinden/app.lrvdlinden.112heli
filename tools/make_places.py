#!/usr/bin/env python3
"""Generates SharedUI/MapPlaces.swift from worker/src/aalerts/locaties.js (A-Alerts, OpenStreetMap ODbL)."""
import json, os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, "worker/src/aalerts/locaties.js")).read()
data = json.loads(src[src.index("{"):src.rindex("}") + 1])
q = lambda s: json.dumps(s or "", ensure_ascii=False)
rows = []
for b in data.get("bases", []):
    rows.append(f'        .init(naam: {q(b["naam"])}, detail: "Basis", kind: .basis, lat: {b["lat"]}, lon: {b["lon"]}),')
for z in data.get("ziekenhuizen", []):
    if not (z.get("helipad") or z.get("trauma")): continue
    bits = [x for x in [z.get("plaats"), "traumacentrum" if z.get("trauma") else None, "helipad" if z.get("helipad") else None] if x]
    rows.append(f'        .init(naam: {q(z["naam"])}, detail: {q(" · ".join(bits))}, kind: .ziekenhuis, lat: {z["lat"]}, lon: {z["lon"]}),')
out = f'''// Generated by tools/make_places.py from the A-Alerts hospitals and bases (OpenStreetMap, ODbL). Do not edit by hand.
import CoreLocation

/// Fixed points of interest on the map: helicopter bases and hospitals with a helipad or trauma centre.
struct MapPlace: Identifiable, Hashable {{
    enum Kind {{ case basis, ziekenhuis }}
    let naam: String
    let detail: String
    let kind: Kind
    let lat: Double
    let lon: Double

    var id: String {{ "\\(naam)-\\(lat)" }}
    var coordinate: CLLocationCoordinate2D {{ CLLocationCoordinate2D(latitude: lat, longitude: lon) }}
    var symbol: String {{ kind == .basis ? "h.circle.fill" : "cross.circle.fill" }}

    static let all: [MapPlace] = [
{chr(10).join(rows)}
    ]
}}
'''
open(os.path.join(root, "SharedUI/MapPlaces.swift"), "w").write(out)
print(len(rows), "places")
